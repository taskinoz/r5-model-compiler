struct CIKRule {
    int index = 0, type = 0, chain = 0, bone = -1, slot = 0;
    float height = 0, radius = 0, floor = 0;
    Vec3 pos;
    Quat q;
    float start = 0, peak = 0, tail = 0, end = 0, contact = 0, drop = 0, top = 0;
    std::string attachment;
    float endHeight = 0;
    // compressed error stream (written relative to the rule)
    std::vector<uint8_t> compressedError;
    float errorScale[6] = {};
    int iStart = 0;
};

struct CMovement {
    int endFrame = 0;
    int motionFlags = 0;
    float v0 = 0, v1 = 0, angle = 0;
    Vec3 vector, position;
};

// Encoded animation (one or more sections, each a chain of per-bone RLE records).
struct CAnimation {
    std::vector<std::vector<uint8_t>> nativeSections;
    bool assetOnly = false;  // left out of the model's table; used by sequence assets
    std::string name;
    float fps = 30;
    int flags = 0;
    int numFrames = 1;
    std::vector<CMovement> movements;
    std::vector<CIKRule> ikRules;
    int sectionFrames = 0;
    std::vector<std::vector<uint8_t>> sections;  // encoded bone chains; one entry when unsectioned
    // frame movement (STUDIO_FRAMEMOVEMENT), already encoded; empty when unused
    std::vector<uint8_t> frameMovement;
    Vec3 bmin, bmax;
};

struct CEvent {
    float cycle = 0;
    int event = 0;
    int type = 0;
    std::string options;
    std::string name;
};

struct CAutoLayer {
    int sequence = 0;
    int pose = 0;
    int flags = 0;
    float start = 0, peak = 0, tail = 0, end = 0;
};

struct CSequence {
    std::string label;
    int assetAnim = -1;  // a referencepose sequence: the clip its standalone asset carries
    std::string activityName;
    int flags = 0;
    int actWeight = 0;
    std::vector<CEvent> events;
    Vec3 bmin, bmax;
    bool explicitBox = false;  // set by the QC; collision does not grow it
    int groupSize[2] = {1, 1};
    std::vector<int16_t> animIndices;  // groupSize[0]*groupSize[1]
    int paramIndex[2] = {-1, -1};
    float paramStart[2] = {0, 0}, paramEnd[2] = {0, 0};
    bool axisRange[2] = {false, false};  // $sequence axisrange: stored as given
    float fadeIn = 0.2f, fadeOut = 0.2f;
    int entryNode = 0, exitNode = 0, nodeFlags = 0;
    float entryPhase = 0, exitPhase = 0;
    float lastFrame = 0;
    int nextSeq = 0, pose = 0;
    int numIKRules = 0;
    std::vector<CAutoLayer> layers;
    // v54 autolayers (32 bytes: asset GUID, int16 pose, int16 0, flags, start/peak/tail/end)
    struct AssetLayer {
        uint64_t guid = 0;
        int pose = 0, flags = 0;
        float start = 0, peak = 0, tail = 0, end = 0;
    };
    std::vector<AssetLayer> assetLayers;
    std::vector<float> weights;  // per bone
    std::vector<float> poseKeys; // groupSize[0] + groupSize[1]
    std::vector<CIKLock> ikLocks;
    std::string keyValues;
    int cyclePose = 0;
    struct ActMod {
        std::string name;
        bool negate = false;
    };
    std::vector<ActMod> activityModifiers;
    int ikResetMask = 0;
    int unkC4 = 0;
    struct UnkCC { float value = 0; int bone = -1; float ramp[4] = {}; };
    std::vector<UnkCC> unkCC;  // seqdesc 0xC8/0xCC table ("unk_cc")
};

// One convex hull of an early-Apex PHY solid (solid space, inches).
struct CApexHull {
    std::vector<Vec3> verts;
    std::vector<std::vector<int>> faces;   // vertex loops, counter-clockwise seen from outside
    std::vector<std::array<int, 4>> edges; // v0, v1, face running v0->v1, face running v1->v0
    Vec3 centroid;
    float innerRadius = 0;  // distance from the centroid to the nearest face plane
};

struct CApexSolid {
    std::vector<CApexHull> hulls;
    double volume = 0;       // of the stored face loops (keyvalue "volume")
    int bone = 0;            // the bone a jointed solid follows
    Vec3 centre;             // volume centroid of the hulls (or $masscenter)
    float inertia[3][3] = {};  // per unit mass, about the solid-space origin
    Vec3 mins, maxs;
};

// Collision output produced by collision.cpp
struct CPhysics {
    std::vector<CApexSolid> apexSolids;  // early-Apex PHY solids; serialised per season
    std::string text;                    // PHY keyvalue text (solids, constraints, editparams)
    int apexPhySize = 0;                 // size of the season's PHY file, recorded in the header
    bool jointed = false;                // $collisionjoints: one solid per bone
    std::vector<uint8_t> phy;  // complete PHY file (header, solids, text)
    float mass = 1;  // studiomdl's default; retail models without physics store 1.0
    int solidCount = 0;
    // Map-collision block (studiohdr collisionOffset) and its count
    std::vector<uint8_t> collisionBlock;
    int staticCollisionCount = 0;
    bool noMapCollision = false;  // header collisionOffset stays 0, as in the retail models without a block
};

// Early-Apex BVH collision block (studiohdr 0x214) and its header fields
struct CBvh {
    std::vector<uint8_t> block;
    Vec3 mins, maxs;          // studiohdr 0x1F0
    int hullEntry = -1, traceEntry = -1;  // studiohdr 0x218
};

// Per-triangle AABB tree for static props
struct CPerTri {
    int version = 0;
    Vec3 bmin, bmax;
    std::vector<uint8_t> data;  // nodes, leaves, verts
    int nodeCount = 0, leafCount = 0, vertCount = 0;
};

struct CompiledModel {
    bool forceComplexWeights = false;
    bool HasComplexWeights() const {
        if (forceComplexWeights) return true;
        for(const auto& bp:bodyParts) for(const auto& md:bp.models)
            for(const auto& mesh:md.meshes) for(const auto& v:mesh.verts)
                if(v.numBones>3) return true;
        return false;
    }
    std::string name;       // internal name, e.g. "props/crate.mdl"
    int flags = 0;
    int extraHeaderFlags = 0;  // $headerflags, ORed in last
    std::map<std::string, int> surfacePropIds;  // lower-case name -> game id (lookups)
    int SurfacePropId(const std::string& propName) const {
        auto it = surfacePropIds.find(ToLower(propName));
        return it == surfacePropIds.end() ? 0 : it->second;
    }
    Vec3 eyePosition, illumPosition;
    Vec3 hullMin, hullMax, viewMin, viewMax;
    float mass = 0;
    int contents = 1;
    std::string surfaceProp = "default";
    std::string keyValues;
    struct SrcBoneTransform {
        std::string bone;
        float pre[12], post[12];
    };
    std::vector<SrcBoneTransform> srcBoneTransforms;
    float fadeDistance = -1;
    uint8_t constDirectionalLightDot = 0;
    uint8_t rootLod = 0, numAllowedRootLods = 0;
    int illumPositionAttachment = 0;
    float maxEyeDeflection = 0;
    std::string unkString;
    std::vector<std::string> sourceFiles;  // stored "source filename" block

    std::vector<CBone> bones;
    std::vector<CJiggle> jiggles;
    std::vector<CAttachment> attachments;
    std::vector<CHitboxSet> hitboxSets;
    std::vector<CAnimation> animations;
    int modelAnimations = -1;  // descriptors in the model's table (asset-only ones follow)
    std::vector<CSequence> sequences;
    std::vector<std::string> textures;  // material names (rename applied)
    bool packedPositions = false;
    bool externalAssetRig = false;
    bool rigAsset = false;  // written as a standalone .rrig
    std::vector<uint8_t> materialTypes; // optional native per-slot shader family
    std::vector<std::string> cdTextures;
    std::vector<std::vector<int16_t>> skins;
    std::vector<std::string> skinNames;  // families 1.. (Apex stores a name for each)  // [family][skinref]
    int numSkinRef = 0;
    std::vector<CBodyPart> bodyParts;
    int numLods = 1;
    bool zeroUnusedLods = false;
    std::vector<float> lodSwitch;  // per LOD
    std::vector<std::vector<std::pair<int, std::string>>> lodMaterialReplacements;  // [lod] -> (texture, name)
    std::vector<std::string> nodeNames;
    int localNodeUnk = 0;
    std::vector<uint8_t> transitions;  // numnodes * numnodes
    std::vector<CIKChain> ikChains;
    std::vector<CUIPanel> uiPanels;
    std::vector<CPoseParam> poseParams;
    std::vector<CIKLock> ikAutoplayLocks;
    std::vector<std::string> includeModels;
    std::vector<int> boneFollowers;

    bool hasVertexColor = false;
    bool hasUV2 = false;

    CPhysics physics;
    bool bvhTrace = false;  // static props get a BVH trace mesh (TF2 wrote a per-tri tree)
    CBvh bvh;
    CPerTri perTri;
};

